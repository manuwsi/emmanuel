def en(html: str) -> str:
    for a, b in T:
        html = html.replace(f'>{a}<', f'>{b}<') if a in ('Par', 'Voir', 'Plans', 'Retours', 'Validé', 'Coût', 'Durée', 'Comparer') else html.replace(a, b)
    # decimal commas in visible numbers: 3,5 s -> 3.5 s ; 0:04,0 -> 0:04.0
    html = re.sub(r'(?<=\d),(?=\d)', '.', html)
    return html


