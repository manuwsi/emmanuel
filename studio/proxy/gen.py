"""Turns the coded prototype (public/proxy/prototype/*.html) into one module the case study can render live.
Run: python3 studio/proxy/gen.py   → writes src/components/proxy/screens.ts
The screens stay the product's own markup: nothing is redrawn, so the page shows the real interface, sharp at any size."""
import re, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'public/proxy/prototype'
OUT = ROOT / 'src/components/proxy/screens.ts'

DESK = {
    'premier-jour': '07-premier-jour.html',
    'aujourdhui': '01-aujourdhui.html',
    'autonomie': '04-autonomie.html',
    'question': '08-question.html',
    'validation': '02-validation.html',
    'journal': '03-journal.html',
    'arret': '05-arret.html',
    'erreur': '09-erreur.html',
    'bilan': '10-bilan.html',
}
PHONE = {'m-accueil': 'm-accueil.html', 'm-journal': 'm-journal.html', 'm-pause': 'm-pause.html'}


def clean(html: str) -> str:
    html = re.sub(r'\s+href="[^"]*"', '', html)          # the screens are shown, not navigated
    html = re.sub(r'\s+class=""', '', html)
    html = re.sub(r'>\s+<', '><', html)                   # no stray whitespace nodes
    return html.strip()


def inner(html: str, opener: str) -> str:
    """inner HTML of the element starting at `opener` (balanced on <div>)"""
    i = html.index(opener)
    j = html.index('>', i) + 1
    depth, k = 1, j
    for m in re.finditer(r'<(/?)div\b', html[j:]):
        depth += -1 if m.group(1) else 1
        if depth == 0:
            k = j + m.start()
            break
    return html[j:k]


screens = {}
for key, f in DESK.items():
    s = (SRC / f).read_text()
    screens[key] = {'w': 1440, 'h': 900, 'html': clean(inner(s, '<div id="stage"'))}
for key, f in PHONE.items():
    s = (SRC / f).read_text()
    screens[key] = {'w': 390, 'h': 844, 'html': clean(inner(s, '<div id="ph"'))}
# the request on the phone: the screen inside the bezel of 06-mobile.html
s = (SRC / '06-mobile.html').read_text()
screens['m-demande'] = {'w': 390, 'h': 844, 'html': clean(inner(s, '<div style="width:390px;height:844px'))}

ts = ['// Generated by studio/proxy/gen.py from public/proxy/prototype — do not edit by hand.',
      'export type ScreenId =', *[f"  | '{k}'" for k in screens], ';', '',
      'export const SCREENS: Record<ScreenId, { w: number; h: number; html: string }> = {']
for k, v in screens.items():
    ts.append(f"  '{k}': {{ w: {v['w']}, h: {v['h']}, html: {json.dumps(v['html'], ensure_ascii=False)} }},")
ts.append('};\n')
OUT.write_text('\n'.join(ts))
print('wrote', OUT, {k: len(v['html']) for k, v in screens.items()})
